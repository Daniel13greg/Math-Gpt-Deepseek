#!/usr/bin/env node
/**
 * Generates `src/components/dom/katex-inline.css` from KaTeX's stylesheet with
 * every font inlined as a base64 woff2 data URI.
 *
 * Why: DOM components ('use dom') bundle CSS but do not copy the font files that
 * katex.css references with relative `url(fonts/...)`, so on device the math
 * fonts would 404. Inlining keeps the WebView fully offline-capable.
 *
 * Re-run after upgrading `katex`:  npm run katex:css
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const katexDist = join(dirname(require.resolve('katex/package.json')), 'dist');
const { version } = require('katex/package.json');

let css = readFileSync(join(katexDist, 'katex.min.css'), 'utf8');

// Each @font-face has `src:url(fonts/X.woff2) format("woff2"),url(fonts/X.woff) ...,url(fonts/X.ttf) ...`.
// Keep only the woff2 source (supported by every WebView we target) and inline it.
let inlined = 0;
css = css.replace(/src:\s*url\(["']?fonts\/([^"')]+)\.woff2["']?\)\s*format\(["']woff2["']\)[^;}]*/g, (_, name) => {
  const data = readFileSync(join(katexDist, 'fonts', `${name}.woff2`)).toString('base64');
  inlined++;
  return `src:url(data:font/woff2;base64,${data}) format("woff2")`;
});

if (inlined === 0 || /url\(["']?fonts\//.test(css)) {
  console.error('build-katex-css: unexpected katex.css format; no fonts were inlined.');
  process.exit(1);
}

const out = join(root, 'src/components/dom/katex-inline.css');
writeFileSync(out, `/* Generated by scripts/build-katex-css.mjs from katex@${version}. Do not edit. */\n${css}\n`);
console.log(`build-katex-css: inlined ${inlined} fonts -> ${out}`);
